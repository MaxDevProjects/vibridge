const assert = require('node:assert/strict')
const { once } = require('node:events')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { test } = require('node:test')
const WebSocket = require('ws')
const { AuthService } = require('../dist/auth')
const { FileService } = require('../dist/files')
const { createServer } = require('../dist/server')

test('workspace files stay within the configured root and skip hidden assets', t => {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'vibridge-files-'))
  t.after(() => fs.rmSync(tmp, { recursive: true, force: true }))
  const root = path.join(tmp, 'workspace')
  const sibling = path.join(tmp, 'workspace-unrelated')
  fs.mkdirSync(root)
  fs.mkdirSync(sibling)
  fs.writeFileSync(path.join(root, 'source.ts'), 'visible')
  fs.writeFileSync(path.join(root, '.env'), 'secret')
  fs.writeFileSync(path.join(sibling, 'outside.txt'), 'outside')
  fs.symlinkSync(sibling, path.join(root, 'linked-directory'))
  fs.symlinkSync(path.join(root, '.env'), path.join(root, 'linked-secret'))
  const files = new FileService(root)
  assert.equal(files.read('source.ts'), 'visible')
  assert.equal(files.read('../workspace-unrelated/outside.txt'), null)
  assert.equal(files.read('linked-directory/outside.txt'), null)
  assert.equal(files.read('.env'), null)
  assert.equal(files.read('linked-secret'), null)
  assert.equal(files.read('outside.txt', sibling), null)
  assert.deepEqual(files.treeFrom(sibling).children, [])
  const mounted = new FileService(root, '/host/projects')
  assert.equal(mounted.read('source.ts', '/host/projects'), 'visible')
  assert.equal(mounted.read('source.ts', '/host/projects-unrelated'), null)
  assert.deepEqual(mounted.treeFrom('/host/projects').children.map(file => file.path), ['source.ts'])
})

test('local pairing requires an existing credential or access to the desktop, and QR tokens expire', async t => {
  const auth = new AuthService()
  assert.equal(auth.consumeQrToken(auth.issueShortLivedToken(0)), false)
  const qr = auth.issueShortLivedToken()
  assert.equal(auth.verify(qr), false)
  assert.equal(auth.consumeQrToken(qr), true)
  assert.equal(auth.consumeQrToken(qr), false)
  const ipc = {}
  const queue = { onOutput: () => () => {} }
  const { httpServer, wss } = createServer({ auth, queue, ipc, PORT: 0 })
  httpServer.listen(0, '127.0.0.1')
  await once(httpServer, 'listening')
  t.after(async () => {
    for (const socket of wss.clients) socket.terminate()
    await Promise.all([new Promise(resolve => wss.close(resolve)), new Promise(resolve => httpServer.close(resolve))])
  })
  const base = `http://127.0.0.1:${httpServer.address().port}`
  for (const endpoint of ['/workspace', '/pairing-code', '/pairing-url']) {
    assert.equal((await fetch(base + endpoint)).status, 401)
  }
  const unverified = new WebSocket(base.replace('http:', 'ws:') + '/ws')
  const mobile = new WebSocket(base.replace('http:', 'ws:') + '/ws')
  await Promise.all([once(unverified, 'open'), once(mobile, 'open')])
  let leaked = false
  unverified.on('message', () => { leaked = true })
  const authenticated = once(mobile, 'message')
  mobile.send(JSON.stringify({ type: 'auth', token: auth.issueToken() }))
  assert.equal(JSON.parse((await authenticated)[0]).type, 'auth_ok')
  const broadcast = once(mobile, 'message')
  ipc.broadcast({ type: 'ide_snapshot', state: { workspaceFolders: ['/test'] } })
  assert.equal(JSON.parse((await broadcast)[0]).type, 'ide_snapshot')
  const closed = once(unverified, 'close')
  unverified.close()
  await closed
  assert.equal(leaked, false)
})
