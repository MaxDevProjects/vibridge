<template>
  <div class="flex flex-col h-[calc(100dvh-3.5rem)] lg:h-[calc(100dvh-3rem)]">
    <WindowStrip :windows="bridge.windows.value" :selected-window-id="bridge.activeWindowId.value"
      :activity="bridge.windowActivity.value" @select="bridge.selectWindow" />
    <p class="px-4 py-2 text-xs border-b border-border" style="color:var(--muted)">
      Aperçu dans {{ bridge.activeProjectName.value || 'le projet sélectionné' }}.
      Pour le moment, seuls les sites accessibles depuis ce navigateur peuvent être ouverts.
      La capture locale Playwright reste à développer.
    </p>
    <p v-if="previewError" class="px-4 py-2 text-xs" role="alert"
      style="color:var(--dot-amber);border-bottom:1px solid var(--border)">
      {{ previewError }}
    </p>
    <!-- Authenticated screenshot generated by Playwright on the local VS Code host. -->
    <section class="border-b border-border p-4 space-y-3 max-h-[65dvh] overflow-y-auto shrink-0">
      <div class="flex items-center justify-between gap-3">
        <div><h2 class="text-sm font-semibold">Capture locale Playwright</h2>
          <p class="text-xs mt-1" style="color:var(--muted)">Aucun tunnel ni port public. Capture du PC via le relay existant.</p></div>
      </div>
      <div class="flex flex-wrap items-center gap-2">
        <label class="text-xs" for="preview-port">Port du serveur</label>
        <input id="preview-port" v-model.number="capturePort" type="number" min="1024" max="65535"
          class="px-2 py-2 w-24 text-xs border border-border bg-surface text-text" />
        <select v-model="captureDevice" class="px-2 py-2 text-xs border border-border bg-surface text-text" aria-label="Taille de la capture">
          <option value="mobile">Mobile · 390 px</option><option value="desktop">Bureau · 1280 px</option>
        </select>
        <button @click="requestCapture" :disabled="captureLoading || bridge.status.value !== 'connected'"
          class="px-4 py-2 text-xs border border-text text-text disabled:opacity-30">
          {{ captureLoading ? 'Capture en cours…' : 'Capturer sur le PC' }}
        </button>
      </div>
      <p v-if="captureError" class="text-xs" style="color:var(--dot-amber)" role="alert">{{ captureError }}</p>
      <p v-if="captureLoading" class="text-xs" style="color:var(--muted)">Demande envoyée à la fenêtre sélectionnée. En attente de l'image. Aucun renvoi automatique.</p>
      <div v-if="screenshotDataUrl" class="space-y-2">
        <p class="text-xs" style="color:var(--muted)">Capture reçue le {{ captureTime }} · fenêtre {{ captureWindowId.slice(0, 6) }}</p>
        <img :src="screenshotDataUrl" alt="Capture Playwright du site local" class="max-w-full h-auto border border-border bg-white mx-auto" />
      </div>
      <p class="text-[11px]" style="color:var(--muted)">Prérequis PC : Playwright + Chromium, et port explicitement autorisé dans les paramètres Utilisateur VS Code.</p>
    </section>
    <!-- TOOLBAR -->
    <div class="flex items-center gap-3 border-b border-border px-4 py-2 shrink-0 flex-wrap">
      <p class="text-xs uppercase tracking-widest text-muted mr-2">APERÇU</p>

      <input
        v-model="urlInput"
        placeholder="http://localhost:5173"
        class="flex-1 min-w-48 bg-surface border border-border text-text text-xs px-3 py-1.5 font-mono focus:outline-none focus:border-text"
        @keydown.enter="applyUrl"
      />
      <button
        class="border border-text text-text text-xs uppercase tracking-widest px-3 py-1.5 hover:bg-surface2 transition-colors"
        @click="applyUrl"
      >
        GO
      </button>
      <button
        class="border border-border text-muted text-xs uppercase tracking-widest px-3 py-1.5 hover:border-text hover:text-text transition-colors"
        @click="reload"
      >
        ↺
      </button>

      <!-- Device width selector -->
      <div class="flex gap-1 ml-auto">
        <button
          v-for="d in devices"
          :key="d.label"
          :class="activeDevice === d.label ? 'border-text text-text' : 'border-border text-muted hover:border-text hover:text-text'"
          class="border text-xs px-2 py-1.5 transition-colors uppercase"
          @click="activeDevice = d.label"
        >
          {{ d.label }}
        </button>
      </div>
    </div>

    <!-- FRAME WRAPPER -->
    <div class="flex-1 overflow-auto flex justify-center items-start bg-surface2 p-4">
      <div
        v-if="activeUrl"
        :style="frameStyle"
        class="bg-bg border border-border overflow-hidden relative"
      >
        <!-- Loading overlay -->
        <div
          v-if="frameLoading"
          class="absolute inset-0 bg-bg flex items-center justify-center text-xs text-muted uppercase tracking-widest"
        >
          CHARGEMENT…
        </div>
        <iframe
          ref="iframeEl"
          :src="activeUrl"
          class="w-full h-full border-none"
          sandbox="allow-scripts allow-same-origin allow-forms allow-popups"
          @load="frameLoading = false"
        />
      </div>
      <div v-else class="text-dimmed text-xs uppercase tracking-widest mt-24">
        — ENTREZ UNE URL POUR PRÉVISUALISER —
      </div>
    </div>
  </div>
</template>

<script setup lang="ts">
import type { WsMessage } from '~/composables/useDevBridge'

const bridge = useDevBridge()

interface Device { label: string; width: number; height: number }

const devices: Device[] = [
  { label: 'FULL', width: 0, height: 0 },
  { label: 'LG', width: 1024, height: 768 },
  { label: 'MD', width: 768, height: 1024 },
  { label: 'SM', width: 390, height: 844 },
]

const urlInput = ref('')
const previewError = ref('')
const activeUrl = ref('')
const activeDevice = ref('FULL')
const frameLoading = ref(false)
const iframeEl = ref<HTMLIFrameElement | null>(null)
const capturePort = ref(5500)
const captureDevice = ref<'mobile' | 'desktop'>('mobile')
const captureLoading = ref(false)
const captureError = ref('')
const screenshotDataUrl = ref('')
const captureTime = ref('')
const captureWindowId = ref('')
let captureTimer: ReturnType<typeof setTimeout> | null = null


const currentDevice = computed(() => devices.find(d => d.label === activeDevice.value) ?? devices[0])

const frameStyle = computed(() => {
  const d = currentDevice.value
  if (!d || d.width === 0) return { width: '100%', height: '70vh' }
  return { width: `${d.width}px`, height: `${d.height}px` }
})

function applyUrl() {
  const url = urlInput.value.trim()
  if (!url) return
  let parsed: URL
  try {
    parsed = new URL(url)
  } catch {
    previewError.value = 'Adresse invalide.'
    return
  }
  if (!['http:', 'https:'].includes(parsed.protocol)) {
    previewError.value = 'Seules les URLs HTTP et HTTPS sont prises en charge.'
    return
  }
  const localhost = ['localhost', '127.0.0.1', '::1'].includes(parsed.hostname)
  const browserLocal = ['localhost', '127.0.0.1', '::1'].includes(window.location.hostname)
  if (localhost && !browserLocal) {
    previewError.value = 'Cette URL localhost est celle du PC et ne fonctionne pas depuis le téléphone. La capture Playwright locale sera nécessaire.'
    activeUrl.value = ''
    return
  }
  if (window.location.protocol === 'https:' && parsed.protocol !== 'https:') {
    previewError.value = 'Le navigateur HTTPS ne peut pas intégrer cette adresse HTTP. Utilise une adresse HTTPS ou une capture distante.'
    activeUrl.value = ''
    return
  }
  previewError.value = ''
  activeUrl.value = parsed.toString()
  frameLoading.value = true
}

function requestCapture() {
  if (captureLoading.value) return
  captureError.value = ''
  screenshotDataUrl.value = ''
  const port = Number(capturePort.value)
  if (!Number.isInteger(port) || port < 1024 || port > 65535) {
    captureError.value = 'Port invalide (1024 à 65535).'
    return
  }
  const windowId = bridge.activeWindowId.value
  if (!windowId || !bridge.selectedWindow.value?.connected) {
    captureError.value = 'Choisis une fenêtre VS Code connectée.'
    return
  }
  captureWindowId.value = windowId
  captureLoading.value = true
  if (!bridge.send({ type: 'preview_capture', port, device: captureDevice.value })) {
    captureLoading.value = false
    captureError.value = 'Impossible d’envoyer la demande. Vérifie le mode contrôle et la connexion.'
    return
  }
  if (captureTimer) clearTimeout(captureTimer)
  captureTimer = setTimeout(() => {
    if (captureLoading.value) {
      captureLoading.value = false
      captureError.value = 'Réponse inconnue. Vérifie la connexion sur le PC avant de réessayer.'
    }
  }, 30_000)
}

function reload() {
  if (!iframeEl.value || !activeUrl.value) return
  frameLoading.value = true
  iframeEl.value.src = activeUrl.value
}

// Listen for dev-server URL from agent — auto-navigate
const offMessage = bridge.onMessage((msg: WsMessage) => {
  if (msg.type === 'preview_capture_result' && captureLoading.value
    && msg.windowId === captureWindowId.value) {
    captureLoading.value = false
    if (captureTimer) clearTimeout(captureTimer)
    captureTimer = null
    if (msg.success === true && typeof msg.image === 'string' && msg.image.length <= 700000) {
      screenshotDataUrl.value = 'data:image/png;base64,' + msg.image
      captureTime.value = new Date().toLocaleTimeString('fr-FR')
      captureError.value = ''
    } else {
      const reasons: Record<string, string> = {
        preview_port_not_authorized_on_pc: 'Port non autorisé : ajoute ce port à devbridge.previewPorts dans les paramètres Utilisateur VS Code.',
        playwright_not_installed_on_pc: 'Playwright non installé sur le PC ou module introuvable.',
        playwright_chromium_not_installed: 'Chromium Playwright n’est pas installé sur le PC.',
        preview_capture_failed: 'Capture impossible. Vérifie le serveur sur localhost, le navigateur et WSL.',
        screenshot_too_large: 'La capture est trop volumineuse.',
        preview_busy: 'Une capture est déjà en cours dans cette fenêtre.',
      }
      captureError.value = reasons[String(msg.error ?? '')] ?? 'Capture refusée ou impossible : ' + String(msg.error ?? 'erreur inconnue')
    }
    return
  }
  if (msg.type === 'dev_server_url' && msg.url && bridge.windows.value.length <= 1) {
    urlInput.value = String(msg.url)
    applyUrl()
  }
})

onMounted(() => {
  const snapshotUrl = bridge.agentStatus.value?.previewUrl
  if (bridge.windows.value.length > 1) {
    previewError.value = 'Détection automatique désactivée en multi-fenêtres : impossible de garantir à quel projet appartient le serveur.'
  } else if (snapshotUrl) {
    urlInput.value = snapshotUrl
    applyUrl()
  } else if (bridge.status.value === 'connected') {
    bridge.send({ type: 'get_preview_url' })
  }
})

watch(() => bridge.activeWindowId.value, () => {
  captureLoading.value = false
  screenshotDataUrl.value = ''
  captureError.value = ''
  if (captureTimer) clearTimeout(captureTimer)
  activeUrl.value = ''
  urlInput.value = ''
  previewError.value = 'Projet changé. Indique une URL accessible depuis ton téléphone.'
})

onUnmounted(() => { offMessage(); if (captureTimer) clearTimeout(captureTimer) })

useHead({ title: 'Aperçu — VibeBridge' })
</script>
